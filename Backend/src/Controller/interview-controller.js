import { PDFParse } from "pdf-parse";
import { generateInterViewReport } from "../Services/AI-service.js";
import { interviewReportModel } from "../Models/InterviewReport-model.js";
import { success } from "zod";

/**
 * @name generateInterviewController
 * @description use to generate report for user on the basis of resume selfDescription and jobDescription
 * @access private
 */
export const generateInterviewController = async (req, res) => {
    try {
        const resumeFile = req.file;
        const resumeText = await (new PDFParse(Uint8Array.from(resumeFile.buffer))).getText();
        const { selfDescription, jobDescription } = req.body;

        const interviewReportByAi = await generateInterViewReport({
            resume: resumeText,
            selfDescription,
            jobDescription
        });
        const interviewReport = await interviewReportModel.create({
            user: req.user.id,
            resume: resumeText.text,
            selfDescription,
            jobDescription,
            ...interviewReportByAi,

        })

        res.status(201).json({
            success: true,
            message: "Interview report generateed successfully",
            data: interviewReport
        })
    } catch (err) {
        return res.status(400).json({
            success: false,
            message: err.message || "Error in generating interview report"
        })

    }

}

